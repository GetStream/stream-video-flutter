// Turns the E2EE worker of @stream-io/video-client into a Dart string, which
// the web EncryptionManager starts as a worker from a blob URL.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { transform } from 'esbuild';

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const clientDir = dirname(require.resolve('@stream-io/video-client/package.json'));
const { version } = JSON.parse(readFileSync(join(clientDir, 'package.json'), 'utf8'));

// The file exports one self-contained function, `e2eeWorker`, that installs
// the worker's listeners when called.
const source = readFileSync(join(clientDir, 'dist/e2ee-worker.browser.es.js'), 'utf8');
const exportLine = /^export \{ e2eeWorker \};$/m;
if (!exportLine.test(source) || /^import /m.test(source)) {
  throw new Error('The E2EE worker of video-client changed shape; update build.mjs.');
}

const { code } = await transform(`${source.replace(exportLine, '')}\ne2eeWorker();\n`, {
  minify: true,
  format: 'iife',
  target: 'es2020',
  legalComments: 'none',
});

// A JSON string is a valid Dart string once `$` is escaped.
const literal = JSON.stringify(code.trim()).replaceAll('$', '\\$');

writeFileSync(
  join(here, '../../lib/src/e2ee/e2ee_worker_source.g.dart'),
  `// GENERATED by tool/e2ee_worker/update.sh. Do not edit.
// The E2EE worker of @stream-io/video-client ${version}.
// ignore_for_file: avoid_escaping_inner_quotes, lines_longer_than_80_chars, prefer_single_quotes

/// The version of @stream-io/video-client [e2eeWorkerSource] comes from.
const e2eeWorkerVersion = '${version}';

/// The script of the E2EE worker.
const e2eeWorkerSource = ${literal};
`,
);
